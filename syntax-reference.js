export function referenceSlug(term) {
  const names = {
    "===": "strict-equality",
    ">=": "greater-than-or-equal",
    "??": "nullish-coalescing",
    "=>": "arrow-function",
    "...": "spread-rest",
    "?.": "optional-chaining",
    "$set": "mongodb-set",
  };
  return names[term] ?? term
    .replace(/^\./, "")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase();
}

